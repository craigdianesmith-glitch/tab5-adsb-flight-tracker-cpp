#!/usr/bin/env python3
"""Generates src/geoid_table.inc: the height of the geoid - mean sea level -
above the WGS84 ellipsoid, in whole metres, every degree, the world over.

An aircraft's GNSS height (the feeds' alt_geom) is above the ellipsoid; less
the geoid there, it is above the sea, near enough. A helicopter's pressure
altitude can be hundreds of feet out on a day of high or low pressure, and
its transponder often never says it is on the ground: the 3D view puts one
by its GNSS height instead, for it to come down onto the ground and lift off
it where it really does (an R44 on the ground at Leicester, 469ft, said 200ft
by its pressure and 491ft by its GNSS less the geoid).

From the NGA's EGM96 model, which is public domain, through PROJ:

    pip install pyproj
    tools/gen_geoid.py

PROJ fetches the model's grid (us_nga_egm96_15) from its CDN the first time.
At a degree apart, read between the four about it, the geoid is within a few
metres of the model.
"""

from pathlib import Path

import pyproj
from pyproj import Transformer

ROOT = Path(__file__).resolve().parent.parent


def main():
    pyproj.network.set_network_enabled(True)
    # A point on the ellipsoid, its height above the geoid: less the geoid's.
    to_geoid = Transformer.from_crs("EPSG:4979", "EPSG:4326+5773", always_xy=True)
    rows = []
    lowest, highest = 1e9, -1e9
    for lat in range(-90, 91):
        row = []
        for lon in range(-180, 181):
            _, _, h = to_geoid.transform(float(lon), float(lat), 0.0)
            n = -h
            lowest, highest = min(lowest, n), max(highest, n)
            row.append(max(-128, min(127, round(n))))
        rows.append(row)
    out = [
        "// Generated by tools/gen_geoid.py from the NGA's EGM96 geoid model - do not",
        "// edit. The geoid's height above the WGS84 ellipsoid, metres: a row a degree",
        "// of latitude from 90S, each 361 a degree of longitude from 180W to 180E.",
        "const int8_t GEOID_M[181][361] = {",
    ]
    for row in rows:
        out.append("    {" + ",".join(str(v) for v in row) + "},")
    out.append("};")
    (ROOT / "src" / "geoid_table.inc").write_text("\n".join(out) + "\n")
    print(f"the geoid from {lowest:.1f}m to {highest:.1f}m above the ellipsoid")


if __name__ == "__main__":
    main()
