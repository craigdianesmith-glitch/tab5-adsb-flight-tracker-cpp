"""Synthesise the on-screen keyboard's key click into src/click_table.inc.

    python tools/gen_click.py [--style tick|tock] [--wav click.wav]

A phone keyboard's click rather than a beep: a key's few milliseconds of
noise, the snap of it, over a short knock that rings and dies away - a
bright, dry "tick", as an Android phone's, picked over the woody "tock" of
an iPhone's that --style tock makes.
The Tab5's speaker has nothing much below 300Hz, so the knock is pitched in
the mid-range rather than as the thud a bigger speaker would give it.

Mono 16-bit at 22.05kHz, 35ms and under 2KB of flash; --wav writes it out
too, to listen to.
"""
import argparse
import math
import random
import struct
import wave

RATE = 22050
SECONDS = 0.035

# The knock's partials - Hz, how loud, how fast each dies away (s) - and the
# snap's: the centre of the band its noise is filtered to, and its decay.
STYLES = {
    "tock": {"partials": [(1250, 1.0, 0.0060), (2650, 0.45, 0.0030), (4100, 0.2, 0.0018)],
             "snap_hz": 3200, "snap_decay": 0.0016, "snap": 0.8},
    "tick": {"partials": [(2200, 0.8, 0.0035), (4600, 0.5, 0.0020)],
             "snap_hz": 5000, "snap_decay": 0.0011, "snap": 1.0},
}


def synth(style):
    s = STYLES[style]
    rnd = random.Random(1007)
    n = int(RATE * SECONDS)
    out = []
    # A two-pole band-pass for the snap's noise, its state carried along.
    f = 2 * math.sin(math.pi * s["snap_hz"] / RATE)
    q = 0.9
    low = band = 0.0
    for i in range(n):
        t = i / RATE
        attack = min(1.0, t / 0.0004)  # a fraction of a millisecond, so it doesn't pop
        knock = sum(a * math.exp(-t / d) * math.sin(2 * math.pi * hz * t) for hz, a, d in s["partials"])
        noise = rnd.uniform(-1, 1)
        high = noise - low - q * band
        band += f * high
        low += f * band
        snap = band * s["snap"] * math.exp(-t / s["snap_decay"])
        out.append(attack * (knock + snap))
    peak = max(abs(v) for v in out)
    # Squeezed a little, as the voice is, so it is heard on the small
    # speaker; and quieter than the voice, being a tap's sound.
    drive = 1.8
    return [math.tanh(drive * v / peak) / math.tanh(drive) * 0.7 for v in out]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--style", default="tick", choices=STYLES)
    ap.add_argument("--out", default="src/click_table.inc")
    ap.add_argument("--wav")
    args = ap.parse_args()
    samples = [int(round(v * 32767)) for v in synth(args.style)]
    with open(args.out, "w") as f:
        f.write("// Generated by tools/gen_click.py - do not edit.\n")
        f.write(f"// The keyboard's key click, a {args.style}, as 16-bit mono samples.\n")
        f.write(f"constexpr uint32_t CLICK_RATE = {RATE};\n")
        f.write(f"const int16_t KEY_CLICK[] = {{  // {len(samples) / RATE * 1000:.0f}ms\n")
        for i in range(0, len(samples), 16):
            f.write("    " + ", ".join(str(v) for v in samples[i:i + 16]) + ",\n")
        f.write("};\n")
    if args.wav:
        with wave.open(args.wav, "wb") as w:
            w.setnchannels(1)
            w.setsampwidth(2)
            w.setframerate(RATE)
            w.writeframes(struct.pack(f"<{len(samples)}h", *samples))
    print(f"{args.out}: {len(samples)} samples, {len(samples) / RATE * 1000:.0f}ms, {len(samples) * 2}B")


if __name__ == "__main__":
    main()
